/**
 * Generates a 4-line ASCII Art banner from a user-provided string.
 * @param input The text to convert, e.g. "KERNEL" or "FADI"
 * @param maxChars Optional limit (default 12 to maintain neat layout)
 */
export function generateAsciiBanner(input: string, maxChars: number = 12): string {
  const sanitized = input.trim().toUpperCase().slice(0, maxChars);
  if (!sanitized) return "";

  const lines: [string, string, string, string] = ["", "", "", ""];

  for (let i = 0; i < sanitized.length; i++) {
    const char = sanitized[i];
    const glyph = ASCII_LETTERS_4LINE[char] || [
      ` ${char} `,
      ` ${char} `,
      ` ${char} `,
      ` ${char} `
    ];

    lines[0] += glyph[0];
    lines[1] += glyph[1];
    lines[2] += glyph[2];
    lines[3] += glyph[3];
  }

  return lines.join("\n");
}
